/*
  THE LEGAL PAGES (2026-10-15): privacy/, terms/, community-guidelines/ and
  support/. The app links all four (Settings > About, sign-up, the paywall),
  and Apple's review needs the privacy and support ones to load and to carry
  real contact details.
  Run with:  node --test
*/
"use strict";

var test = require("node:test");
var assert = require("node:assert/strict");
var fs = require("node:fs");
var path = require("node:path");

var root = path.join(__dirname, "..");
var PAGES = ["privacy", "terms", "community-guidelines", "support"];

function read(page) {
  return fs.readFileSync(path.join(root, page, "index.html"), "utf8");
}

test("every legal page exists, runs no script, and loads nothing from another host", function () {
  PAGES.forEach(function (page) {
    var html = read(page);
    assert.match(html, /default-src 'none'; style-src 'self'/, page);
    assert.doesNotMatch(html, /<script/i, page + " has a script");
    assert.doesNotMatch(html, /fonts\.googleapis|<link[^>]+href="https?:/i, page + " loads from another host");
    assert.match(html, /href="\.\.\/legal\.css"/, page);
  });
});

test("each page links the other three, and marks itself as the current one", function () {
  PAGES.forEach(function (page) {
    var html = read(page);
    PAGES.forEach(function (other) {
      if (other === page) assert.match(html, /<a href="\.\/" aria-current="page">/, page);
      else assert.ok(html.includes('href="../' + other + '/"'), page + " -> " + other);
    });
  });
});

test("privacy and support name a real contact address", function () {
  ["privacy", "support", "community-guidelines"].forEach(function (page) {
    assert.match(read(page), /mailto:hello@makullveny\.com/, page);
  });
});

test("privacy covers what Apple asks a policy to cover", function () {
  var html = read("privacy");
  ["How long we keep it", "Deleting your data", "Who helps us", "Students under 18", "Delete my Makullveny data only", "Delete my account from ALL TDG apps", "RevenueCat", "Stripe", "Show me as Anonymous", "Focus Points and Selah leaderboards", "IP address", "TDG's admins"].forEach(function (words) {
    assert.ok(html.includes(words), "privacy is missing: " + words);
  });
});

test("the terms page is the generated agreement: 21 sections and the version line", function () {
  var html = read("terms");
  assert.match(html, /GENERATED by tools\/build-terms\.mjs/);
  assert.equal((html.match(/<section class="terms-section" id="a\d+">/g) || []).length, 21);
  assert.match(html, /Version 2\.2 — 15 October 2026/);
  assert.match(html, /id="a20">\s*<h2>A20\. People you study with<\/h2>/);
  assert.match(html, /id="a21">\s*<h2>A21\. Contact<\/h2>/);
});
