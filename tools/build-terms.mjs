// THE TERMS PAGE IS GENERATED, never hand-edited (2026-10-15).
//
// terms/index.html is the Makullveny agreement word for word: Part A of the
// app's LICENSE, kept in the app repo as build/eula-source.txt (the same text
// the Windows installer shows). A hand-copied web version is exactly the copy
// that drifts, so this reads that file and writes the page.
//
//   node tools/build-terms.mjs ../Makullveny/build/eula-source.txt
//
// tests/legal-pages.test.js checks the page carries every section heading.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
if (!source) {
  console.error("usage: node tools/build-terms.mjs <path to build/eula-source.txt>");
  process.exit(1);
}

const text = readFileSync(source, "utf8").replace(/^﻿/, "").replace(/\r\n/g, "\n");
const version = (text.match(/^Version .+$/m) || ["Version unknown"])[0];

function esc(value) {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// Links are added AFTER escaping, and only for the addresses this agreement
// names on purpose.
function linkify(html) {
  return html
    .replace(/hello@makullveny\.com/g, '<a href="mailto:hello@makullveny.com">hello@makullveny.com</a>')
    .replace(/makullveny\.com\/(privacy|community-guidelines|support)\//g, '<a href="../$1/">makullveny.com/$1/</a>')
    .replace(/reportaproblem\.apple\.com/g, '<a href="https://reportaproblem.apple.com">reportaproblem.apple.com</a>');
}

const flat = (lines) => lines.map((line) => line.trim()).join(" ");

// One blank-line-separated block of the agreement, as HTML.
function block(raw) {
  const lines = raw.split("\n").filter((line) => line.trim());
  if (!lines.length) return "";
  const item = lines[0].match(/^\s+([a-z])\.\s+(.*)$/);
  if (item) {
    // A lettered item, possibly with numbered sub-items "(1) ..." under it.
    // A line back at the item's own indent (5 spaces) after the sub-items is
    // the item's closing sentence ("Either way, ..."), not part of the last one.
    const rest = [item[2], ...lines.slice(1)];
    const parts = [];
    const after = [];
    let current = [];
    for (const line of rest) {
      // Only where the sub-items wrap at 9 spaces: A6g's sub-items wrap at 5,
      // so a 5-space line there is still inside its sub-item.
      const deep = current.some((l) => /^ {9}\S/.test(l));
      if (after.length || (parts.length && deep && /^ {5}\S/.test(line) && !/^\s*\(\d+\)/.test(line))) { after.push(line); continue; }
      if (/^\s*\(\d+\)\s/.test(line) && current.length) { parts.push(current); current = []; }
      current.push(line);
    }
    parts.push(current);
    const lead = linkify(esc(flat(parts[0])));
    const subs = parts.slice(1).map((p) => `<li>${linkify(esc(flat(p).replace(/^\(\d+\)\s*/, "")))}</li>`).join("");
    const tail = after.length ? `<p class="item-tail">${linkify(esc(flat(after)))}</p>` : "";
    return `<p class="item"><strong>${item[1]}.</strong> ${lead}</p>${subs ? `<ol class="sub">${subs}</ol>` : ""}${tail}`;
  }
  // "  Email: ..." contact lines keep one line each.
  if (lines.every((line) => /^\s{2}\S/.test(line)) && lines.length > 1) {
    return `<ul class="lines">${lines.map((l) => `<li>${linkify(esc(l.trim()))}</li>`).join("")}</ul>`;
  }
  return `<p>${linkify(esc(flat(lines)))}</p>`;
}

const firstSection = text.search(/^A1\. /m);
const head = text.slice(0, firstSection);
const body = text.slice(firstSection);

// The preamble, without the title and version lines (the page has its own).
const preamble = head.split("\n").slice(2).join("\n").trim().split(/\n\s*\n/).map(block).join("\n        ");

const sections = body.split(/^(?=A\d+\. )/m).map((chunk) => {
  const [heading, ...rest] = chunk.split("\n");
  const id = heading.match(/^(A\d+)\./)[1].toLowerCase();
  const title = heading.replace(/^A\d+\.\s*/, "");
  const blocks = rest.join("\n").trim().split(/\n\s*\n/).map(block).join("\n          ");
  return `      <section class="terms-section" id="${id}">
        <h2>${esc(heading.match(/^A\d+/)[0])}. ${esc(title.charAt(0) + title.slice(1).toLowerCase())}</h2>
          ${blocks}
      </section>`;
}).join("\n");

const page = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <!-- GENERATED by tools/build-terms.mjs from the app repo's
         build/eula-source.txt. Do not edit by hand: edit that file, then run
         the tool. The owner approves every word of the source. -->
    <meta name="description" content="The Makullveny agreement: what you may do with the app, what stays yours, paying, refunds, safety and contact.">
    <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'">
    <meta name="referrer" content="no-referrer">
    <title>Terms · Makullveny</title>
    <link rel="icon" href="../assets/icons/icon.svg" type="image/svg+xml">
    <link rel="stylesheet" href="../legal.css">
  </head>
  <body>
    <nav class="legal-top" aria-label="Makullveny pages">
      <a class="home" href="../">Makullveny</a>
      <a href="../privacy/">Privacy</a>
      <a href="./" aria-current="page">Terms</a>
      <a href="../community-guidelines/">Community Guidelines</a>
      <a href="../support/">Support</a>
    </nav>
    <main>
      <h1>Terms of Use</h1>
      <p class="updated">${esc(version)}. This is the Makullveny end user licence agreement, the same text the app shows.</p>
      <div class="preamble">
        ${preamble}
      </div>
${sections}
    </main>
    <footer>Makullveny · Nate McIlvenny and Luke McIlvenny, doing business as TDG</footer>
  </body>
</html>
`;

writeFileSync(join(here, "..", "terms", "index.html"), page);
console.log(`terms/index.html written from ${source} (${version})`);
